function getNextLeapYear() {

    const currentYear = new Date().getFullYear();

    let year = currentYear + 1;

    while (!isLeapYear(year)) {
        year++;
    }

    return String(year);
}

function isLeapYear(year) {

    return (
        year % 400 === 0 ||
        (year % 4 === 0 && year % 100 !== 0)
    );

}


